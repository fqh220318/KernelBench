"""Validate the maintainer-only operator pool and render its review index.

This is deliberately a collection tool, not a task generator.  A row in the
pool means that its source and licence were inspected and that it is worth a
maintainer decision.  It does not mean that the row has passed a MUSA device
run, the B-tier gap gate, or the baseline gate.

Usage:

    python musa_operator_eval/evaluator/collect_operator_candidate_pool.py
    python musa_operator_eval/evaluator/collect_operator_candidate_pool.py --check
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
REPOSITORY_ROOT = ROOT.parent
POOL_PATH = ROOT / "sources" / "operator_candidate_pool.json"
OUTPUT_PATH = ROOT / "sets" / "candidates" / "CANDIDATE_POOL.md"
ATTENTION_POOL_PATH = ROOT / "sources" / "attention_operator_candidate_pool.json"
ATTENTION_OUTPUT_PATH = ROOT / "sets" / "candidates" / "ATTENTION_CANDIDATE_POOL.md"
POOL_OUTPUTS = {
    "general": (POOL_PATH, OUTPUT_PATH),
    "attention": (ATTENTION_POOL_PATH, ATTENTION_OUTPUT_PATH),
}
EVALUATOR_DIR = Path(__file__).resolve().parent
if str(EVALUATOR_DIR) not in sys.path:
    sys.path.insert(0, str(EVALUATOR_DIR))

from validate_schemas import validate_instance  # noqa: E402


DECISION_ZH = {
    "shortlisted": "入围",
    "needs_probe": "待探测",
    "deferred": "暂缓",
}

TIER_ZH = {
    "promising": "有希望",
    "needs_gap_probe": "待缺口探测",
    "needs_redesign": "需重设计",
    "not_suitable": "不适合",
}

EVIDENCE_ZH = {
    "local_measured_plus_source": "本地历史测量 + 多源代码",
    "multi_source_code": "多源代码交叉证据",
    "official_source_code": "官方源码证据",
    "lead_only": "仅线索",
}


def load_pool(path: Path = POOL_PATH) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def pool_errors(pool: dict[str, Any]) -> list[str]:
    """Schema/business checks plus repository-local evidence checks."""

    errors = validate_instance(pool, "operator_candidate_pool", engine="stdlib")
    candidates = pool.get("candidates", [])
    for index, candidate in enumerate(candidates):
        prefix = f"candidates[{index}]"
        for anchor in candidate.get("local_anchors", []):
            path = REPOSITORY_ROOT / anchor["path"]
            if not path.exists():
                errors.append(f"{prefix}.local_anchors: missing {anchor['path']!r}")
    return errors


def _repository_link(source: dict[str, Any]) -> str:
    revision = source["revision"]
    return f"[{source['project']}]({source['repository']}/tree/{revision})"


def _joined(values: list[str]) -> str:
    return "、".join(f"`{value}`" for value in values)


def render(pool: dict[str, Any]) -> str:
    summary = pool["summary"]
    source_by_id = {item["source_id"]: item for item in pool["sources"]}
    candidates_by_family: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for candidate in pool["candidates"]:
        candidates_by_family[candidate["family_id"]].append(candidate)

    lines = [
        f"# {pool['title']}",
        "",
        "<!-- Generated by musa_operator_eval/evaluator/collect_operator_candidate_pool.py. Do not edit by hand. -->",
        "",
        f"采集日期：`{pool['collected_on']}`。本文件是维护者评审索引，不是 Agent 题面，也不是硬件验证报告。",
        "",
        "> “源码存在”只证明候选可研究；`hardware_validated=false` 表示尚未在记录过的 MUSA 环境中按当前评测协议构建和测量。B 类的 gap 也只是待验证假设。",
        "",
        "## 汇总",
        "",
        "| 来源 | family | 候选 | 入围 | 待探测 | 暂缓 | 已硬件验证 |",
        "|---:|---:|---:|---:|---:|---:|---:|",
        (
            f"| {summary['source_count']} | {summary['family_count']} | {summary['candidate_count']} | "
            f"{summary['shortlisted']} | {summary['needs_probe']} | {summary['deferred']} | "
            f"{summary['hardware_validated']} |"
        ),
        "",
        "## 证据来源",
        "",
        "| source | 权威级别 | Commit | License | 当前验证状态 |",
        "|---|---|---|---|---|",
    ]

    authority_zh = {
        "local_repository": "本地仓库",
        "vendor_official": "厂商官方",
        "community_project": "社区项目",
    }
    for source in pool["sources"]:
        lines.append(
            f"| {_repository_link(source)} | {authority_zh[source['authority']]} | "
            f"`{source['revision'][:12]}` | `{source['license']}` | "
            f"`{source['validation_status']}` |"
        )

    lines.extend([
        "",
        "## Family 概览",
        "",
        "| family | 候选数 | 入围数 | 选择依据 |",
        "|---|---:|---:|---|",
    ])
    for family in pool["families"]:
        rows = candidates_by_family[family["family_id"]]
        shortlisted = sum(item["decision"] == "shortlisted" for item in rows)
        lines.append(
            f"| `{family['family_id']}` {family['title']} | {len(rows)} | {shortlisted} | "
            f"{family['selection_reason']} |"
        )

    lines.extend([
        "",
        "## 候选决策表",
        "",
        "| 优先级 | candidate | family | 决策 | A 类判断 | B 类判断 | 证据 |",
        "|---|---|---|---|---|---|---|",
    ])
    for candidate in sorted(pool["candidates"], key=lambda item: (item["priority"], item["family_id"], item["candidate_id"])):
        lines.append(
            f"| `{candidate['priority']}` | `{candidate['candidate_id']}` {candidate['name']} | "
            f"`{candidate['family_id']}` | {DECISION_ZH[candidate['decision']]} | "
            f"{TIER_ZH[candidate['a_tier']['status']]} | {TIER_ZH[candidate['b_tier']['status']]} | "
            f"{EVIDENCE_ZH[candidate['evidence_level']]} |"
        )

    lines.extend(["", "## 逐 family 评审信息", ""])
    for family in pool["families"]:
        lines.extend([
            f"### {family['title']} (`{family['family_id']}`)",
            "",
            f"语义契约必须重点固定：{_joined(family['semantic_contract_focus'])}。",
            "",
        ])
        for candidate in candidates_by_family[family["family_id"]]:
            sources = [source_by_id[source_id]["project"] for source_id in candidate["source_refs"]]
            lines.extend([
                f"#### `{candidate['candidate_id']}` — {candidate['name']}",
                "",
                f"- 决策：**{DECISION_ZH[candidate['decision']]}**；优先级 `{candidate['priority']}`；硬件验证：`{str(candidate['hardware_validated']).lower()}`。",
                f"- 语义范围：{candidate['semantic_scope']}",
                f"- 动态维度：{_joined(candidate['dynamic_dimensions'])}。",
                f"- 来源：{'、'.join(sources)}。",
                f"- A 类：{TIER_ZH[candidate['a_tier']['status']]}。{candidate['a_tier']['rationale']}",
                f"- B 类：{TIER_ZH[candidate['b_tier']['status']]}。{candidate['b_tier']['rationale']}",
            ])
            if candidate["b_tier"]["gap_hypotheses"]:
                lines.append(
                    f"- B 类待测 gap 假设：{_joined(candidate['b_tier']['gap_hypotheses'])}；它们尚不是实测证据。"
                )
            if candidate["local_anchors"]:
                anchors = "；".join(f"`{item['path']}` ({item['role']})" for item in candidate["local_anchors"])
                lines.append(f"- 本地锚点：{anchors}。")
            lines.extend([
                f"- 风险：{'；'.join(candidate['risks'])}。",
                f"- 下一证据：{'；'.join(candidate['next_evidence'])}。",
                "",
            ])

    lines.extend(["## 未纳入范围", ""])
    for item in pool["exclusions"]:
        lines.append(f"- **{item['scope']}**：{item['reason']}")

    lines.extend([
        "",
        "## 晋级为正式任务前的硬门槛",
        "",
        "1. 将上游源码、Commit、LICENSE、原始实现和测试做不可变快照，仍保持 maintainer-only。",
        "2. 为 family 单独编写语义契约和 CPU reference，不能复用 Attention 专属字段。",
        "3. 按 A/B 三问重新判级；B 类必须实测至少 3 条 gap、至少 2 类原因和 naive/expert >= 1.3。",
        "4. 生成公开 smoke、隐藏正确性/边界/极值/性能 Case 与运行时泛化探针。",
        "5. 在同一 MUSA 环境采齐 A 的 4 个基线角色或 B 的 6 个基线角色，readiness 为 complete 后才可发布或排名。",
        "",
        f"发布规则：{pool['release_rule']}",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify JSON and generated Markdown without writing")
    parser.add_argument(
        "--pool",
        choices=("all", *POOL_OUTPUTS),
        default="all",
        help="select one pool; the default validates or regenerates every maintained pool",
    )
    args = parser.parse_args()

    selected = POOL_OUTPUTS.items() if args.pool == "all" else [(args.pool, POOL_OUTPUTS[args.pool])]
    failed = False
    for pool_name, (pool_path, output_path) in selected:
        try:
            pool = load_pool(pool_path)
        except (OSError, json.JSONDecodeError) as error:
            print(f"FAIL {pool_path}: {error}")
            failed = True
            continue

        errors = pool_errors(pool)
        if errors:
            print(f"FAIL {pool_path}")
            for error in errors:
                print(f"  {error}")
            failed = True
            continue

        rendered = render(pool)
        if args.check:
            if not output_path.exists():
                print(f"FAIL missing generated index {output_path}")
                failed = True
                continue
            current = output_path.read_text(encoding="utf-8").replace("\r\n", "\n")
            if current != rendered.replace("\r\n", "\n"):
                print(f"FAIL stale generated index {output_path}")
                failed = True
                continue
            print(
                f"ok {pool_name}: {pool['summary']['candidate_count']} candidates across "
                f"{pool['summary']['family_count']} families; generated index current"
            )
            continue

        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(rendered, encoding="utf-8", newline="\n")
        print(f"wrote {output_path}")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
